export const messages = { ar, en };
export function t(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
// Apply direction isolation only to display strings, never to executed commands.
export function commandDisplay(command: string): string { return '\u2066' + command + '\u2069'; }
